def read_jasc(path):
    with open(path) as f:
        lines = f.read().strip().split("\n")
    c = []
    for line in lines[3:]:
        p = line.strip().split()
        if len(p) >= 3:
            c.append((int(p[0]), int(p[1]), int(p[2])))
    return c[:16]

def apply_pal(img, pal):
    w, h = img.size
    px = list(img.getdata())
    out = Image.new("RGBA", (w, h))
    op = []
    for idx in px:
        if idx == 0:
            op.append((0, 0, 0, 0))
        elif idx < len(pal):
            op.append(pal[idx] + (255,))
        else:
            op.append((0, 0, 0, 0))
    out.putdata(op)
    return out

def darken(c, f=0.6):
    return (int(c[0]*f), int(c[1]*f), int(c[2]*f))

def lighten(c, f=1.3):
    return (min(255,int(c[0]*f)), min(255,int(c[1]*f)), min(255,int(c[2]*f)))

