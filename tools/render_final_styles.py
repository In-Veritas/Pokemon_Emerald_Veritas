# Brendan palette roles:
# 5: hat/pants/jacket lighter, 6: hat/pants/jacket main, 7: unused darker, 8: bandana/jacket/shoe outline
# 9: white hat parts, 10: bandana left/bag sash, 11: bandana right/bag/socks, 12: neck/pokeball/hands, 13: tshirt/shoes
# May palette roles:
# 5: outfit lighter, 6: outfit dark, 7: HAIR LIGHT, 8: HAIR DARK
# 9: light clothing, 10-11: bandana/bag (same as brendan), 12-13: accents (same as brendan)

def make_design(clothes_main, clothes_light=None, clothes_outline=None,
                bag_main=None, bag_shadow=None, accent_main=None, accent_dark=None,
                white_parts=None, hat_white=None, hair=None):
    """Returns (male_pal, female_pal) tuple.
    hair=None means keep original, hair=(light,dark) means change May's hair."""
    cm = clothes_main
    cl = clothes_light or lighten(cm, 1.35)
    co = clothes_outline or darken(cm, 0.45)
    cu = darken(cm, 0.7)
    bm = bag_main or lighten(cm, 1.5)
    bs = bag_shadow or darken(bm, 0.65)
    am = accent_main or (255, 98, 90)
    ad = accent_dark or darken(am, 0.7)
    wp = white_parts or (222, 230, 238)
    hw = hat_white or (255, 255, 255)

    male = list(em_m)
    male[5] = cl; male[6] = cm; male[7] = cu; male[8] = co
    male[9] = wp; male[10] = bm; male[11] = bs
    male[12] = am; male[13] = ad; male[14] = hw

    female = list(em_f)
    female[5] = cl; female[6] = cm
    # May indices 7-8 are HAIR - keep original unless explicitly changed
    if hair:
        female[7] = hair[0]; female[8] = hair[1]
    # else: keep em_f[7] and em_f[8] (original brown hair)
    female[9] = wp; female[10] = bm; female[11] = bs
    female[12] = am; female[13] = ad; female[14] = hw

    return male, female

